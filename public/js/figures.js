function panel(pose, dx) {
  return `<g transform="translate(${dx},0)">${draw(pose)}</g>`;
}

/**
 * 動作說明頁的詳細示意圖。沒畫過的回傳 null。
 */
export function guideFigure(key) {
  const g = GUIDE[key];
  if (!g) return null;
  const w = PW * 2 + GAP;
  const mid = PW + GAP / 2;

  let s = panel(g.a, 0) + panel(g.b, PW + GAP);

  // 中間的箭頭
  s += `<g class="f-step"><line x1="${mid - 9}" y1="58" x2="${mid + 9}" y2="58"/>`
    + `<polyline points="${mid + 3},52 ${mid + 9},58 ${mid + 3},64"/></g>`;

  // 兩格的標題
  s += `<text x="${PW / 2}" y="122" class="f-label">${g.la}</text>`
    + `<text x="${PW + GAP + PW / 2}" y="122" class="f-label">${g.lb}</text>`;

  return `<svg class="figsvg figsvg-wide" viewBox="0 0 ${w} 130" role="img" aria-hidden="true">${s}</svg>`;
}

/**
 * 取得某一檔的示範圖。沒有畫過的檔位回傳 null，呼叫端自己決定怎麼辦
 * （目前的做法是整塊不顯示，不要放一個破圖）。
 */
export function figureSVG(ladderKey, tierIndex) {
  const id = ladderKey + ':' + tierIndex;
  const pose = POSES[id] || POSES[ALIAS[id]];
  if (!pose) return null;
  return `<svg class="figsvg" viewBox="0 0 ${W} ${H}" role="img" aria-hidden="true">${draw(pose)}</svg>`;
}

export function hasFigure(ladderKey, tierIndex) {
  const id = ladderKey + ':' + tierIndex;
  return !!(POSES[id] || POSES[ALIAS[id]]);
}
