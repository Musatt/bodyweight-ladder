//
//  畫法：每個動作就是一組關節座標，由下面的 draw() 連成線。
//  這樣 27 張圖會是「同一個人」，不會每張畫風不同。
//
//  座標系統：viewBox 是 160 寬 × 104 高，地面在 y=96。
//  x 由左到右、y 由上到下（y 越大越低，跟螢幕一樣）。
//
//  一個姿勢的欄位：
//    head  頭的中心 [x, y]
//    sh    肩膀 [x, y]        ← 軀幹就是 sh 到 hip 這條線
//    hip   髖部 [x, y]
//    arms  手臂，每隻是 [[手肘], [手腕]]，從 sh 出發
//    legs  腿，每條是 [[膝], [踝], [腳尖]]，從 hip 出發
//    props 道具，看下面 PROPS 支援哪些
//
//  想加新的一張圖：照上面的格式在 POSES 裡加一筆，
//  鍵是「階梯代號:檔位編號」，檔位編號從 0 開始算（T1 是 0）。
// ============================================================

const W = 160, H = 104, GROUND = 96;

// ---------- 道具 ----------

function props(list) {
  let s = '';
  for (const p of list || []) {
    const [kind, a, b, c, d] = p;
    if (kind === 'ground') {
      s += `<line x1="6" y1="${GROUND}" x2="${W - 6}" y2="${GROUND}" class="f-ground"/>`;
    } else if (kind === 'mat') {
      s += `<line x1="6" y1="${GROUND}" x2="${W - 6}" y2="${GROUND}" class="f-mat"/>`;
    } else if (kind === 'wall') {
      s += `<line x1="${a}" y1="8" x2="${a}" y2="${GROUND}" class="f-ground"/>`;
    } else if (kind === 'bar') {
      // 單槓：一條橫槓加兩個固定點
      s += `<line x1="34" y1="${a}" x2="126" y2="${a}" class="f-prop"/>`
        +  `<line x1="34" y1="${a - 5}" x2="34" y2="${a + 5}" class="f-ground"/>`
        +  `<line x1="126" y1="${a - 5}" x2="126" y2="${a + 5}" class="f-ground"/>`;
    } else if (kind === 'box') {
      // 椅子／台階／流理台
      s += `<rect x="${a}" y="${b}" width="${c - a}" height="${d - b}" class="f-prop"/>`;
    } else if (kind === 'up' || kind === 'down') {
      // 動作方向的箭頭
      const dir = kind === 'up' ? -1 : 1;
      s += `<line x1="${a}" y1="${b}" x2="${a}" y2="${b + dir * 22}" class="f-arrow"/>`
        +  `<polyline points="${a - 4},${b + dir * 15} ${a},${b + dir * 22} ${a + 4},${b + dir * 15}" class="f-arrow"/>`;
    } else if (kind === 'square') {
      // 「在空中畫方形」用的提示
      s += `<rect x="${a}" y="${b}" width="16" height="16" class="f-arrow" stroke-dasharray="3 3"/>`;
    }
  }
  return s;
}

// ---------- 把一組關節畫成人 ----------

function draw(p) {
  const [hx, hy] = p.head;
  let s = props(p.props);

  // 軀幹
  s += `<line x1="${p.sh[0]}" y1="${p.sh[1]}" x2="${p.hip[0]}" y2="${p.hip[1]}" class="f-body"/>`;
  // 脖子（肩膀連到頭）
  s += `<line x1="${p.sh[0]}" y1="${p.sh[1]}" x2="${hx}" y2="${hy}" class="f-body"/>`;

  for (const [el, wr] of p.arms || []) {
    s += `<polyline points="${p.sh[0]},${p.sh[1]} ${el[0]},${el[1]} ${wr[0]},${wr[1]}" class="f-limb"/>`;
  }
  for (const [kn, an, toe] of p.legs || []) {
    s += `<polyline points="${p.hip[0]},${p.hip[1]} ${kn[0]},${kn[1]} ${an[0]},${an[1]}${toe ? ' ' + toe[0] + ',' + toe[1] : ''}" class="f-limb"/>`;
  }

  // 頭最後畫，才會蓋在脖子上面
  s += `<circle cx="${hx}" cy="${hy}" r="7" class="f-head"/>`;
  return s;
}

